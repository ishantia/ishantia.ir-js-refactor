export default function Icon({ name, className = "", size = 18, ariaHidden = true, ...props }) {
  // normalize names like "fa-solid fa-rocket" or "rocket"
  let cleanName = name;
  if (cleanName.includes("fa-")) {
    const match = cleanName.match(/fa-([a-z0-9\-]+)/g);
    if (match && match.length) {
      // Pick the last segment (e.g. from ["fa-solid", "fa-rocket"] -> "rocket")
      const candidate = match[match.length - 1].replace("fa-", "");
      if (candidate !== "solid" && candidate !== "brands" && candidate !== "regular") {
        cleanName = candidate;
      }
    }
  }

  const path = ICON_PATHS[cleanName];

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={`app-icon icon-${cleanName} ${className}`}
      aria-hidden={ariaHidden ? "true" : undefined}
      {...props}
    >
      {path || (
        <circle cx="12" cy="12" r="8" stroke="currentColor" strokeWidth="2" />
      )}
    </svg>
  );
}
